"""Create and manage isolated SQL Server schemas for upload sessions.

Workspace names are generated by this module; callers must never supply an
arbitrary SQL identifier. A workspace is a schema named ``ws_<uuid hex>``.
"""

from __future__ import annotations

import re
import uuid

import pyodbc

from .db_conn import DatabaseUtil


_WORKSPACE_PATTERN = re.compile(r"^ws_[0-9a-f]{32}$")


class WorkspaceManager:
    """Manage per-session schemas in the configured SQL Server database."""

    def __init__(self, db: DatabaseUtil | None = None) -> None:
        self.db = db or DatabaseUtil()

    @staticmethod
    def _validate_workspace_name(workspace_name: str) -> str:
        """Accept only names generated in the expected workspace format."""
        if not isinstance(workspace_name, str) or not _WORKSPACE_PATTERN.fullmatch(workspace_name):
            raise ValueError("Invalid workspace name.")
        return workspace_name

    def create_workspace(self) -> str:
        """Create and return a new, unique workspace schema name."""
        workspace_name = f"ws_{uuid.uuid4().hex}"
        connection = self.db.get_connection()
        cursor = connection.cursor()

        try:
            # The identifier is generated locally and constrained to hex chars.
            cursor.execute(f"CREATE SCHEMA [{workspace_name}]")
            connection.commit()
            return workspace_name
        except Exception:
            connection.rollback()
            raise
        finally:
            cursor.close()
            connection.close()

    def workspace_exists(self, workspace_name: str) -> bool:
        """Return whether a valid workspace schema exists."""
        workspace_name = self._validate_workspace_name(workspace_name)
        connection = self.db.get_connection()
        cursor = connection.cursor()

        try:
            cursor.execute(
                "SELECT 1 FROM sys.schemas WHERE name = ?",
                (workspace_name,),
            )
            return cursor.fetchone() is not None
        finally:
            cursor.close()
            connection.close()

    def drop_workspace(self, workspace_name: str) -> None:
        """Drop only a generated workspace schema and its contained tables.

        This is intended for explicit session cleanup, not for normal uploads.
        It refuses dbo and any schema that does not match the generated format.
        """
        workspace_name = self._validate_workspace_name(workspace_name)
        connection = self.db.get_connection()
        cursor = connection.cursor()

        try:
            cursor.execute(
                "SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES "
                "WHERE TABLE_SCHEMA = ? AND TABLE_TYPE = 'BASE TABLE'",
                (workspace_name,),
            )
            table_names = [row[0] for row in cursor.fetchall()]

            for table_name in table_names:
                safe_table = table_name.replace("]", "]]" )
                cursor.execute(
                    f"DROP TABLE [{workspace_name}].[{safe_table}]"
                )

            cursor.execute(f"DROP SCHEMA [{workspace_name}]")
            connection.commit()
        except Exception:
            connection.rollback()
            raise
        finally:
            cursor.close()
            connection.close()
